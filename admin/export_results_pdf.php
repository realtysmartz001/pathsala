<?php
session_start();
require_once __DIR__ . '/../includes/db_connect.php';
require_once __DIR__ . '/../vendor/autoload.php';
use Dompdf\Dompdf;
use Dompdf\Options;
if (!isset($_SESSION['role']) || $_SESSION['role'] !== "admin") {
    header("Location: ../auth/login.php");
    exit();
}
date_default_timezone_set('Asia/Kolkata');

// ── Same filter logic as view_results.php, so the PDF matches whatever
// the admin currently has searched/filtered on screen ──
$where = "1=1";
if (!empty($_GET['search'])) {
    $search = mysqli_real_escape_string($conn, $_GET['search']);
    $where .= " AND (u.name LIKE '%$search%' OR u.email LIKE '%$search%')";
}
if (!empty($_GET['set_no'])) {
    $set_no = mysqli_real_escape_string($conn, $_GET['set_no']);
    $where .= " AND ua.set_no = '$set_no'";
}
if (!empty($_GET['from_date']) && !empty($_GET['to_date'])) {
    $from = $_GET['from_date'];
    $to = $_GET['to_date'];
    $where .= " AND DATE(ua.submitted_at) BETWEEN '$from' AND '$to'";
}

$sql = "SELECT ua.*, u.name, u.email, u.extra_attempt, u.is_guest
        FROM user_attempts ua
        JOIN users u ON ua.user_id = u.id
        WHERE $where
        ORDER BY ua.submitted_at DESC";
$result = mysqli_query($conn, $sql);
$total = mysqli_num_rows($result);

function pdf_esc($v)
{
    return htmlspecialchars($v ?? '', ENT_QUOTES, 'UTF-8');
}

$generatedOn = date('d M Y, h:i A');
$exportedBy = htmlspecialchars_decode($_SESSION['admin_name'] ?? 'Admin');

// Build a short label for what filter was applied (shown in the PDF header)
$filterParts = [];
if (!empty($_GET['search'])) {
    $filterParts[] = 'Search: "' . pdf_esc($_GET['search']) . '"';
}
if (!empty($_GET['set_no'])) {
    $filterParts[] = 'Set: ' . pdf_esc($_GET['set_no']);
}
if (!empty($_GET['from_date']) && !empty($_GET['to_date'])) {
    $filterParts[] = 'Date: ' . pdf_esc($_GET['from_date']) . ' to ' . pdf_esc($_GET['to_date']);
}
$filterLabel = !empty($filterParts) ? implode(' &nbsp;|&nbsp; ', $filterParts) : 'All Records';

/* Build HTML report */
$css = '
    @page { margin: 100px 30px 60px 30px; }
    body { font-family: "DejaVu Sans", sans-serif; color: #222; font-size: 10px; }
    .header {
        position: fixed; top: -80px; left: 0px; right: 0px; height: 78px;
        text-align: center; border-bottom: 2px solid #C9933A; padding-bottom: 8px;
    }
    .header .company { font-size: 20px; font-weight: bold; color: #C9933A; }
    .header .title { font-size: 13px; font-weight: bold; color: #1A1A2E; margin-top: 2px; }
    .header .filter-label { font-size: 9.5px; color: #888; margin-top: 4px; }
    .footer {
        position: fixed; bottom: -50px; left: 0px; right: 0px; height: 44px;
        border-top: 1px solid #ddd; padding-top: 6px; font-size: 9px; color: #777;
    }
    .footer table { width: 100%; }
    .footer td { padding: 1px 0; }
    .page-number:before { content: counter(page); }
    .summary-row { margin-bottom: 14px; }
    .summary-row table { width: 100%; }
    .summary-row td {
        background: #fafafa; border: 1px solid #eee; padding: 8px 10px;
        text-align: center; width: 33.33%;
    }
    .summary-num { font-size: 16px; font-weight: bold; color: #1A1A2E; }
    .summary-lbl { font-size: 9px; color: #888; text-transform: uppercase; margin-top: 2px; }
    table.results-table { width: 100%; border-collapse: collapse; }
    table.results-table th {
        background: #C9933A; color: #fff; padding: 6px 6px; font-size: 9px;
        text-align: left; border: 1px solid #C9933A;
    }
    table.results-table td {
        padding: 6px 6px; font-size: 9px; border: 1px solid #eee; vertical-align: top;
    }
    table.results-table tr:nth-child(even) td { background: #fafafa; }
    .guest-tag { color: #6a1b9a; font-weight: bold; font-size: 8px; }
    .tab-bad { color: #C62828; font-weight: bold; }
    .tab-good { color: #2E7D32; font-weight: bold; }
    .score-cell { font-weight: bold; }
';

$bodyHtml = '';
$bodyHtml .= '<div class="header">';
$bodyHtml .= '<div class="company">Realty Smartz Pathshala</div>';
$bodyHtml .= '<div class="title">TEST RESULTS REPORT</div>';
$bodyHtml .= '<div class="filter-label">' . $filterLabel . '</div>';
$bodyHtml .= '</div>';

$bodyHtml .= '<div class="footer"><table><tr>';
$bodyHtml .= '<td style="text-align:left;">Generated By: Realty Smartz Pathshala Admin &nbsp;|&nbsp; Exported By: ' . pdf_esc($exportedBy) . '</td>';
$bodyHtml .= '<td style="text-align:right;">Confidential &nbsp;|&nbsp; Page <span class="page-number"></span></td>';
$bodyHtml .= '</tr></table></div>';

$bodyHtml .= '<div class="summary-row"><table><tr>';
$bodyHtml .= '<td><div class="summary-num">' . $total . '</div><div class="summary-lbl">Records in this report</div></td>';
$bodyHtml .= '<td><div class="summary-num">' . pdf_esc($generatedOn) . '</div><div class="summary-lbl">Generated on</div></td>';
$bodyHtml .= '</tr></table></div>';

$bodyHtml .= '<table class="results-table">';
$bodyHtml .= '<thead><tr>';
$bodyHtml .= '<th>#</th><th>User</th><th>Email</th><th>Attempt</th><th>Set</th><th>Score</th><th>Tab Switches</th><th>Started</th><th>Submitted</th>';
$bodyHtml .= '</tr></thead><tbody>';

if ($total > 0) {
    $i = 1;
    while ($row = mysqli_fetch_assoc($result)) {
        $startedAt = (!empty($row['start_time']) && $row['start_time'] !== '0000-00-00 00:00:00')
            ? date('d M Y, h:i A', strtotime($row['start_time']))
            : '—';
        $submittedAt = (!empty($row['end_time']) && $row['end_time'] !== '0000-00-00 00:00:00')
            ? date('d M Y, h:i A', strtotime($row['end_time']))
            : '—';
        $tabClass = ($row['tab_switches'] > 0) ? 'tab-bad' : 'tab-good';
        $guestTag = !empty($row['is_guest']) ? ' <span class="guest-tag">(Guest)</span>' : '';

        $bodyHtml .= '<tr>';
        $bodyHtml .= '<td>' . $i++ . '</td>';
        $bodyHtml .= '<td>' . pdf_esc($row['name']) . $guestTag . '</td>';
        $bodyHtml .= '<td>' . pdf_esc($row['email']) . '</td>';
        $bodyHtml .= '<td>Attempt ' . (int) $row['attempt_no'] . '</td>';
        $bodyHtml .= '<td>' . pdf_esc($row['set_no']) . '</td>';
        $bodyHtml .= '<td class="score-cell">' . (int) $row['score'] . '</td>';
        $bodyHtml .= '<td class="' . $tabClass . '">' . (int) ($row['tab_switches'] ?? 0) . '</td>';
        $bodyHtml .= '<td>' . pdf_esc($startedAt) . '</td>';
        $bodyHtml .= '<td>' . pdf_esc($submittedAt) . '</td>';
        $bodyHtml .= '</tr>';
    }
} else {
    $bodyHtml .= '<tr><td colspan="9" style="text-align:center; padding:20px; color:#999;">No records found for this filter.</td></tr>';
}

$bodyHtml .= '</tbody></table>';

$fullHtml = '<!DOCTYPE html><html><head><meta charset="UTF-8"><style>' . $css . '</style></head><body>' . $bodyHtml . '</body></html>';

/* Render PDF */
$options = new Options();
$options->set('isRemoteEnabled', false);
$options->set('isHtml5ParserEnabled', true);
$options->set('defaultFont', 'DejaVu Sans');
$dompdf = new Dompdf($options);
$dompdf->loadHtml($fullHtml);
$dompdf->setPaper('A4', 'landscape');
$dompdf->render();

$filename = 'Test_Results_Report_' . date('Y-m-d') . '.pdf';
while (ob_get_level()) {
    ob_end_clean();
}
$dompdf->stream($filename, array('Attachment' => true));
exit();